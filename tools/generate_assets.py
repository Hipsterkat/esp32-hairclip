#!/usr/bin/env python3
"""Generate the firmware's font table and embedded web page.

Outputs (committed; regenerate after editing web/, the char map in
hairclip/text.cpp or the font choice below):

  hairclip/generated_fonts.h  font selection and metrics measured from the
                              U8g2 glyph bitmaps
  hairclip/generated_web.h    web/index.html with preview.js, app.js, the
                              glyph data and the char map inlined, gzipped,
                              plus the matching Content-Security-Policy

Usage:
  python3 tools/generate_assets.py               write both headers
  python3 tools/generate_assets.py --check       exit 1 if they are stale
  python3 tools/generate_assets.py --html FILE   also write the page, uncompressed
"""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))

from u8g2font import U8g2Font, find_u8g2_fonts_c, load_font  # noqa: E402

FONTS = [  # (API id, label, U8g2 font) in FontSize order
    ("small", "Small", "u8g2_font_helvB08_te"),
    ("medium", "Medium", "u8g2_font_helvB12_te"),
    ("large", "Large", "u8g2_font_helvB18_te"),
]

FONTS_HEADER = ROOT / "hairclip" / "generated_fonts.h"
WEB_HEADER = ROOT / "hairclip" / "generated_web.h"
INLINE_MARKER = "<!-- @inline-scripts -->"


def displayable() -> list[int]:
    """Must match text::isDisplayable() in hairclip/text.cpp."""
    return list(range(0x20, 0x7F)) + list(range(0xA0, 0x17F)) + list(range(0x218, 0x21C))


def u8g2_version(fonts_c: Path) -> str:
    props = fonts_c.parents[2] / "library.properties"
    if props.is_file():
        for line in props.read_text().splitlines():
            if line.startswith("version="):
                return line.split("=", 1)[1].strip()
    return "unknown"


def load_fonts() -> tuple[list[U8g2Font], str]:
    path = find_u8g2_fonts_c()
    fonts = [U8g2Font(load_font(name, path)) for _, _, name in FONTS]
    for f in fonts:
        missing = [cp for cp in displayable() if not f.has(cp)]
        if missing:
            raise SystemExit(f"{f.name} lacks glyphs for " + ", ".join(f"U+{c:04X}" for c in missing))
    return fonts, u8g2_version(path)


def line_set() -> list[int]:
    """Characters the two-line slots are sized for: ASCII, Latin-1, Romanian."""
    return list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [ord(c) for c in "ĂăȘșȚțŞşŢţ"]


def metrics(font: U8g2Font) -> dict:
    cap = font.extents(range(0x20, 0x7F))
    line = font.extents(line_set())
    mx = font.extents(displayable())
    return {"capAscent": cap[0], "capDescent": cap[1], "lineAscent": line[0], "lineDescent": line[1],
            "maxAscent": mx[0], "maxDescent": mx[1]}


# ---------------------------------------------------------------------------
# generated_fonts.h
# ---------------------------------------------------------------------------

def fonts_header(fonts: list[U8g2Font], version: str) -> str:
    out = [
        f"// GENERATED by tools/generate_assets.py from U8g2 {version}. Do not edit.",
        "// Metrics are measured from the glyph bitmaps: \"cap\" over ASCII, \"line\" over",
        "// ASCII + Latin-1 + Romanian, \"max\" over every displayable character.",
        "#pragma once",
        "",
        '#include "layout.h"',
        "",
    ]
    for (fid, _, name) in FONTS:
        out.append(f"#define HAIRCLIP_FONT_{fid.upper()} {name}")
    out += ["", "inline constexpr const char* kFontLabels[FONT_COUNT] = {"]
    out += [f'    "{label}",' for _, label, _ in FONTS]
    out += ["};", "", "inline constexpr FontMetrics kFontMetrics[FONT_COUNT] = {"]
    for (fid, _, name), f in zip(FONTS, fonts):
        m = metrics(f)
        values = ", ".join(str(m[k]) for k in ("capAscent", "capDescent", "lineAscent", "lineDescent",
                                               "maxAscent", "maxDescent"))
        out.append(f"    {{{values}}},  // {fid}: {name}")
    out.append("};")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# generated_web.h
# ---------------------------------------------------------------------------

def charmap() -> list:
    """The kCharMap table from hairclip/text.cpp, for the browser preview."""
    src = (ROOT / "hairclip" / "text.cpp").read_text(encoding="utf-8")
    block = src[src.index("// BEGIN CHARMAP"):src.index("// END CHARMAP")]
    entries = re.findall(r'\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+),\s*"((?:[^"\\]|\\.)*)"\}', block)
    if not entries:
        raise SystemExit("no CHARMAP entries found in hairclip/text.cpp")
    return [[int(a, 16), int(b, 16), r.encode("ascii").decode("unicode_escape")] for a, b, r in entries]


def font_blob(font: U8g2Font) -> str:
    data = bytearray(font.data[:23])
    for cp in displayable():
        bits = font.glyph_bits(cp)
        data += bytes([cp >> 8, cp & 0xFF, len(bits)]) + bits
    return base64.b64encode(bytes(data)).decode("ascii")


def strip_lines(text: str) -> str:
    """Drop indentation and blank lines. Safe for this code base: no
    multi-line template literals or strings are used."""
    return "\n".join(line.strip() for line in text.splitlines() if line.strip())


def minify_js(js: str) -> str:
    js = re.sub(r"(?ms)^\s*/\*.*?\*/\s*$", "", js)  # whole-line block comments
    js = re.sub(r"(?m)^\s*//.*$", "", js)  # whole-line // comments
    return strip_lines(js)


def build_page(fonts: list[U8g2Font]) -> tuple[str, str]:
    """Returns (html, csp)."""
    html = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    font_data = {
        fid: {"label": label, "metrics": metrics(f), "data": font_blob(f)}
        for (fid, label, _), f in zip(FONTS, fonts)
    }
    data_js = (
        "const HC_FONTS=" + json.dumps(font_data, separators=(",", ":"))
        + ";\nconst HC_CHARMAP=" + json.dumps(charmap(), separators=(",", ":")) + ";"
    ).replace("</", "<\\/")
    code = minify_js(
        (ROOT / "web" / "preview.js").read_text(encoding="utf-8")
        + "\n"
        + (ROOT / "web" / "app.js").read_text(encoding="utf-8")
    )
    script = data_js + "\n" + code
    if INLINE_MARKER not in html:
        raise SystemExit(f"{INLINE_MARKER} missing from web/index.html")
    html = strip_lines(html.replace(INLINE_MARKER, "@@SCRIPT@@"))
    html = html.replace("@@SCRIPT@@", "<script>" + script + "</script>")
    style = re.search(r"<style>(.*?)</style>", html, re.S).group(1)

    def sha(s: str) -> str:
        return base64.b64encode(hashlib.sha256(s.encode("utf-8")).digest()).decode("ascii")

    csp = (
        "default-src 'none'; "
        f"script-src 'sha256-{sha(script)}'; "
        f"style-src 'sha256-{sha(style)}'; "
        "connect-src 'self'; img-src data:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"
    )
    return html, csp


def web_header(html: str, csp: str) -> str:
    raw = html.encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    digest = hashlib.sha256(raw).hexdigest()
    out = [
        "// GENERATED by tools/generate_assets.py from web/. Do not edit.",
        f"// Page: {len(raw)} bytes, sha256 {digest}; {len(gz)} bytes gzipped.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const char WEB_CSP[] = {json.dumps(csp)};",
        f"static const size_t WEB_INDEX_GZ_LEN = {len(gz)};",
        "static const uint8_t WEB_INDEX_GZ[] = {",
    ]
    for i in range(0, len(gz), 20):
        out.append("    " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def check(fonts_h: str, html: str, csp: str) -> int:
    problems = []
    if not FONTS_HEADER.is_file() or FONTS_HEADER.read_text() != fonts_h:
        problems.append(f"{FONTS_HEADER.relative_to(ROOT)} is out of date")
    current = WEB_HEADER.read_text() if WEB_HEADER.is_file() else ""
    digest = hashlib.sha256(html.encode("utf-8")).hexdigest()
    # gzip bytes may differ between zlib builds, so compare the page hash and CSP.
    if f"sha256 {digest};" not in current or json.dumps(csp) not in current:
        problems.append(f"{WEB_HEADER.relative_to(ROOT)} is out of date")
    for p in problems:
        print(f"STALE: {p}. Run: python3 tools/generate_assets.py", file=sys.stderr)
    if not problems:
        print("generated headers are up to date")
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify the committed headers instead of writing")
    ap.add_argument("--html", type=Path, help="also write the uncompressed page here")
    args = ap.parse_args()

    fonts, version = load_fonts()
    fonts_h = fonts_header(fonts, version)
    html, csp = build_page(fonts)
    if args.html:
        args.html.write_text(html, encoding="utf-8")
    if args.check:
        return check(fonts_h, html, csp)
    FONTS_HEADER.write_text(fonts_h)
    WEB_HEADER.write_text(web_header(html, csp))
    gz_len = len(gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0))
    print(f"wrote {FONTS_HEADER.relative_to(ROOT)} (U8g2 {version})")
    print(f"wrote {WEB_HEADER.relative_to(ROOT)} ({len(html.encode('utf-8'))} bytes page, {gz_len} gzipped)")
    for (fid, _, name), f in zip(FONTS, fonts):
        print(f"  {fid:6} {name:22} {metrics(f)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
